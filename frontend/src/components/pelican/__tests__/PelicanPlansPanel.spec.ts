import { flushPromises, mount } from '@vue/test-utils'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import PelicanPlansPanel from '../PelicanPlansPanel.vue'

const models = vi.hoisted(() => vi.fn())
vi.mock('@/api/pelicanTests', () => ({ listPelicanPlanModels: models, listPelicanPlanAccounts: vi.fn(async () => []) }))

const groups = [{ id: 3, name: '授权分组' }, { id: 4, name: '备用分组' }]
const plan = { id: 7, group_id: 3, group_name: '授权分组', model_id: 'gpt-test', interval_minutes: 30, enabled: false, max_results: 20, min_chars: 9366, daily_call_limit: 0, failure_pause_threshold: 0, retention_days: 0, daily_calls_used: 0, usage_day: '2026-09-17', consecutive_failed_runs: 0, pause_reason: '', estimated_calls_per_run: 1, last_run_calls: 0, created_at: '', updated_at: '' }
const wrappers: ReturnType<typeof mount>[] = []
const mountPanel = () => { const wrapper = mount(PelicanPlansPanel, { props: { loading: false, groups, plans: [plan] }, global: { stubs: { teleport: true } } }); wrappers.push(wrapper); return wrapper }
const openCreate = async (wrapper: ReturnType<typeof mount>) => wrapper.findAll('button').find(button => button.text() === '新建计划')!.trigger('click')

describe('PelicanPlansPanel', () => {
  beforeEach(() => models.mockReset())
  afterEach(() => { wrappers.splice(0).forEach(wrapper => wrapper.unmount()) })
  it('opens the loaded plan directly and switches plans within the same editor', async () => {
    models.mockResolvedValue(['gpt-test'])
    const wrapper = mountPanel()
    await wrapper.setProps({ loading: true, openEditorOnLoad: true })
    expect(wrapper.find('.editor-panel').exists()).toBe(false)
    await wrapper.setProps({ loading: false, plans: [plan, { ...plan, id: 8, interval_minutes: 120 }] })
    await flushPromises()
    expect((wrapper.get('select[aria-label="当前计划"]').element as HTMLSelectElement).value).toBe('7')
    await wrapper.get('select[aria-label="当前计划"]').setValue('8'); await flushPromises()
    expect((wrapper.get('input[aria-label="间隔分钟"]').element as HTMLInputElement).value).toBe('120')
    await wrapper.get('form').trigger('submit')
    expect(wrapper.emitted('save')?.[0]).toEqual([8, expect.objectContaining({ interval_minutes: 120 })])
    await wrapper.get('select[aria-label="当前计划"]').setValue('')
    expect(wrapper.get('button[type="submit"]').text()).toBe('新建计划')
    await wrapper.findAll('button').find(button => button.text() === '返回计划列表')!.trigger('click')
    await wrapper.setProps({ loading: true })
    await wrapper.setProps({ loading: false })
    expect(wrapper.find('.editor-panel').exists()).toBe(false)
  })

  it('opens creation directly for an empty loaded list, but not for a failed load', async () => {
    const wrapper = mountPanel()
    await wrapper.setProps({ plans: [], loading: true, openEditorOnLoad: true, error: '加载失败' })
    await wrapper.setProps({ loading: false })
    expect(wrapper.find('.editor-panel').exists()).toBe(false)
    await wrapper.setProps({ loading: true, error: '' })
    await wrapper.setProps({ loading: false })
    expect(wrapper.get('button[type="submit"]').text()).toBe('新建计划')
    expect((wrapper.get('select[aria-label="当前计划"]').element as HTMLSelectElement).value).toBe('')
  })
  it('creates multiple models in selection order and round-trips that order when editing', async () => {
    models.mockResolvedValue(['gpt-a', 'gpt-b', 'gpt-c'])
    const wrapper = mountPanel()
    await openCreate(wrapper)
    await wrapper.get('select[aria-label="分组"]').setValue('3'); await flushPromises()
    await wrapper.get('input[aria-label="gpt-b"]').setValue(true)
    await wrapper.get('input[aria-label="gpt-a"]').setValue(true)
    expect(wrapper.findAll('.selected-models li').map(node => node.text())).toEqual(['gpt-b', 'gpt-a'])
    expect(wrapper.get('.model-estimate').text()).toContain('每轮预估 2 次调用')
    await wrapper.get('form').trigger('submit')
    expect(wrapper.emitted('save')?.[0]).toEqual([null, expect.objectContaining({ model_id: 'gpt-b', model_ids: ['gpt-b', 'gpt-a'] })])
    await wrapper.setProps({ plans: [{ ...plan, model_id: 'gpt-b', model_ids: ['gpt-b', 'gpt-a'] }] })
    await wrapper.findAll('button').find(button => button.text() === '编辑')!.trigger('click'); await flushPromises()
    await wrapper.get('form').trigger('submit')
    expect(wrapper.emitted('save')?.[1]).toEqual([7, expect.objectContaining({ model_id: 'gpt-b', model_ids: ['gpt-b', 'gpt-a'] })])
    await wrapper.get('input[aria-label="gpt-b"]').setValue(false)
    await wrapper.get('input[aria-label="gpt-c"]').setValue(true)
    await wrapper.get('form').trigger('submit')
    expect(wrapper.emitted('save')?.[2]).toEqual([7, expect.objectContaining({ model_id: 'gpt-a', model_ids: ['gpt-a', 'gpt-c'] })])
  })

  it('clears all selected models on group switch even when model IDs overlap', async () => {
    models.mockResolvedValue(['gpt-a', 'gpt-b'])
    const wrapper = mountPanel()
    await openCreate(wrapper)
    await wrapper.get('select[aria-label="分组"]').setValue('3'); await flushPromises()
    await wrapper.get('input[aria-label="gpt-a"]').setValue(true)
    await wrapper.get('input[aria-label="gpt-b"]').setValue(true)
    await wrapper.get('select[aria-label="分组"]').setValue('4'); await flushPromises()
    expect(wrapper.findAll('.model-options input:checked')).toHaveLength(0)
    expect(wrapper.findAll('.selected-models li')).toHaveLength(0)
    expect(wrapper.get('button[type="submit"]').attributes('disabled')).toBeDefined()
    await wrapper.get('form').trigger('submit')
    expect(wrapper.emitted('save')).toBeUndefined()
  })

  it('limits a plan to ten models and allows replacing one selection', async () => {
    models.mockResolvedValue(Array.from({ length: 11 }, (_, index) => `gpt-${index}`))
    const wrapper = mountPanel()
    await openCreate(wrapper)
    await wrapper.get('select[aria-label="分组"]').setValue('3'); await flushPromises()
    for (let index = 0; index < 10; index++) await wrapper.get(`input[aria-label="gpt-${index}"]`).setValue(true)
    expect(wrapper.get('input[aria-label="gpt-10"]').attributes('disabled')).toBeDefined()
    await wrapper.get('input[aria-label="gpt-0"]').setValue(false)
    expect(wrapper.get('input[aria-label="gpt-10"]').attributes('disabled')).toBeUndefined()
    await wrapper.get('input[aria-label="gpt-10"]').setValue(true)
    await wrapper.get('form').trigger('submit')
    expect(wrapper.emitted('save')?.[0]).toEqual([null, expect.objectContaining({
      model_id: 'gpt-1', model_ids: Array.from({ length: 10 }, (_, index) => `gpt-${index + 1}`)
    })])
  })

  it('renders an actual plan and only submits a selected configured model', async () => {
    models.mockResolvedValue(['gpt-test'])
    const wrapper = mountPanel()
    expect(wrapper.text()).toContain('授权分组')
    expect(wrapper.text()).toContain('gpt-test')
    await wrapper.findAll('button').find(button => button.text() === '立即运行')!.trigger('click')
    expect(wrapper.emitted('run')?.[0]).toEqual([7])
    await openCreate(wrapper)
    await wrapper.get('select[aria-label="分组"]').setValue('3'); await flushPromises()
    expect(wrapper.get('button[type="submit"]').attributes('disabled')).toBeDefined()
    await wrapper.get('input[aria-label="gpt-test"]').setValue(true)
    await wrapper.get('form').trigger('submit')
    expect(wrapper.emitted('save')?.[0]).toEqual([null, expect.objectContaining({ group_id: 3, model_id: 'gpt-test', enabled: false, interval_minutes: 60, max_results: 5, min_chars: 9366, daily_call_limit: 0, failure_pause_threshold: 0, retention_days: 0 })])
    expect(wrapper.text()).toContain('每日用量按 UTC+8 重置')
    expect(wrapper.text()).toContain('每轮由分组调度选择一个账号，最多测试一次')
    expect((wrapper.get('select[aria-label="思考强度"]').element as HTMLSelectElement).value).toBe('')
  })

  it('saves a custom timeout and restores it when editing', async () => {
    models.mockResolvedValue(['gpt-test'])
    const wrapper = mountPanel()
    await openCreate(wrapper)
    expect((wrapper.get('input[aria-label="测试超时秒"]').element as HTMLInputElement).value).toBe('180')
    await wrapper.get('select[aria-label="分组"]').setValue('3'); await flushPromises()
    await wrapper.get('input[aria-label="gpt-test"]').setValue(true)
    await wrapper.get('input[aria-label="测试超时秒"]').setValue('1800')
    await wrapper.get('form').trigger('submit')
    expect(wrapper.emitted('save')?.[0]).toEqual([null, expect.objectContaining({ timeout_seconds: 1800 })])
    await wrapper.setProps({ plans: [{ ...plan, timeout_seconds: 3600 }] })
    await wrapper.findAll('button').find(button => button.text() === '编辑')!.trigger('click'); await flushPromises()
    expect((wrapper.get('input[aria-label="测试超时秒"]').element as HTMLInputElement).value).toBe('3600')
  })

  it('round-trips the selected reasoning effort through create and edit', async () => {
    models.mockResolvedValue(['gpt-test'])
    const wrapper = mountPanel()
    await openCreate(wrapper)
    await wrapper.get('select[aria-label="分组"]').setValue('3'); await flushPromises()
    await wrapper.get('input[aria-label="gpt-test"]').setValue(true)
    await wrapper.get('select[aria-label="思考强度"]').setValue('xhigh')
    await wrapper.get('form').trigger('submit')
    expect(wrapper.emitted('save')?.[0]).toEqual([null, expect.objectContaining({ reasoning_effort: 'xhigh' })])

    await wrapper.setProps({ plans: [{ ...plan, reasoning_effort: 'minimal' }] })
    await wrapper.findAll('button').find(button => button.text() === '编辑')!.trigger('click'); await flushPromises()
    expect((wrapper.get('select[aria-label="思考强度"]').element as HTMLSelectElement).value).toBe('minimal')
    await wrapper.get('form').trigger('submit')
    expect(wrapper.emitted('save')?.[1]).toEqual([7, expect.objectContaining({ reasoning_effort: 'minimal' })])
  })

  it('includes cost and retention settings in edited plan payloads without resuming an auto-paused plan', async () => {
    models.mockResolvedValue(['gpt-test'])
    const wrapper = mountPanel()
    await wrapper.findAll('button').find(button => button.text() === '编辑')!.trigger('click'); await flushPromises()
    await wrapper.get('input[aria-label="每日调用上限"]').setValue('50')
    await wrapper.get('input[aria-label="连续失败暂停阈值"]').setValue('3')
    await wrapper.get('select[aria-label="按天保留"]').setValue('30')
    await wrapper.get('form').trigger('submit')
    expect(wrapper.emitted('save')?.[0]).toEqual([7, expect.objectContaining({ daily_call_limit: 50, failure_pause_threshold: 3, retention_days: 30 })])
    await wrapper.setProps({ plans: [{ ...plan, pause_reason: 'consecutive_failures', enabled: false }] })
    await wrapper.findAll('button').find(button => button.text() === '编辑')!.trigger('click'); await flushPromises()
    expect(wrapper.text()).toContain('请使用下方“恢复计划”')
    expect(wrapper.get('label.enabled input[type="checkbox"]').attributes('disabled')).toBeDefined()
  })

  it('emits explicit resume and named cleanup scopes', async () => {
    const wrapper = mountPanel()
    await wrapper.setProps({ plans: [{ ...plan, pause_reason: 'consecutive_failures' }] })
    await wrapper.findAll('button').find(button => button.text() === '恢复计划')!.trigger('click')
    await wrapper.get('.plan-more summary').trigger('click')
    await wrapper.findAll('button').find(button => button.text() === '清理失败/跳过记录')!.trigger('click')
    await wrapper.findAll('button').find(button => button.text() === '按保留规则清理')!.trigger('click')
    expect(wrapper.emitted('resume')?.[0]).toEqual([7])
    expect(wrapper.emitted('cleanup-request')).toEqual([[expect.objectContaining({ id: 7 }), 'failed'], [expect.objectContaining({ id: 7 }), 'expired']])
  })

  it('ignores stale group model responses and clears the previous selection immediately', async () => {
    models.mockImplementation((groupID: number) => new Promise<string[]>(resolve => setTimeout(() => resolve(groupID === 3 ? ['gpt-three'] : ['gpt-four']), groupID === 3 ? 20 : 0)))
    const wrapper = mountPanel()
    await openCreate(wrapper)
    await wrapper.get('select[aria-label="分组"]').setValue('3')
    await wrapper.get('select[aria-label="分组"]').setValue('4')
    await new Promise(resolve => setTimeout(resolve, 30)); await flushPromises()
    expect((wrapper.get('select[aria-label="分组"]').element as HTMLSelectElement).value).toBe('4')
    expect(wrapper.text()).toContain('gpt-four')
    expect(wrapper.text()).not.toContain('gpt-three')
    expect(wrapper.findAll('.model-options input:checked')).toHaveLength(0)
  })

  it('keeps a valid edited model, and makes an invalid edited model require reselection', async () => {
    models.mockResolvedValueOnce(['gpt-test']).mockResolvedValueOnce(['gpt-new'])
    const wrapper = mountPanel()
    await wrapper.findAll('button').find(button => button.text() === '编辑')!.trigger('click'); await flushPromises()
    expect((wrapper.get('input[aria-label="gpt-test"]').element as HTMLInputElement).checked).toBe(true)
    await wrapper.setProps({ plans: [{ ...plan, id: 8, model_id: 'gpt-old' }] })
    await wrapper.findAll('button').find(button => button.text() === '编辑')!.trigger('click'); await flushPromises()
    expect(wrapper.findAll('.model-options input:checked')).toHaveLength(0)
    expect(wrapper.text()).toContain('原模型已不在该分组的可选模型中，请重新选择。')
    expect(wrapper.get('button[type="submit"]').attributes('disabled')).toBeDefined()
  })

  it('shows a retryable model-load error and blocks submission', async () => {
    models.mockRejectedValueOnce(new Error('目录暂不可用')).mockResolvedValueOnce(['gpt-retry'])
    const wrapper = mountPanel()
    await openCreate(wrapper)
    await wrapper.get('select[aria-label="分组"]').setValue('3'); await flushPromises()
    expect(wrapper.text()).toContain('无法加载模型：目录暂不可用')
    expect(wrapper.get('button[type="submit"]').attributes('disabled')).toBeDefined()
    await wrapper.findAll('button').find(button => button.text() === '重试')!.trigger('click'); await flushPromises()
    expect(wrapper.text()).toContain('gpt-retry')
  })

  it('keeps the editor collapsed until requested and filters plan statuses', async () => {
    const wrapper = mountPanel()
    expect(wrapper.find('form').exists()).toBe(false)
    expect(wrapper.get('.overview-grid').text()).toContain('启用中')
    await wrapper.setProps({ plans: [plan, { ...plan, id: 8, group_name: '运行分组', enabled: true }, { ...plan, id: 9, group_name: '暂停分组', pause_reason: 'consecutive_failures' }] })
    expect(wrapper.get('.overview-grid').text()).toContain('自动暂停')
    await wrapper.get('select[aria-label="筛选计划"]').setValue('paused')
    expect(wrapper.findAll('.plan-card')).toHaveLength(1)
    expect(wrapper.get('.plan-card').text()).toContain('暂停分组')
    await openCreate(wrapper)
    expect(wrapper.find('form').exists()).toBe(true)
    await wrapper.findAll('button').find(button => button.text() === '返回计划列表')!.trigger('click')
    expect(wrapper.find('form').exists()).toBe(false)
  })
})
