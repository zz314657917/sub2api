    expect(leaderboardView).toContain("item.rank_new")
    expect(leaderboardView).toContain("t('leaderboard.rankChangeNew')")
    expect(leaderboardView).toContain('function leaderboardRankComparedLabel')
    expect(leaderboardView).toContain("t('leaderboard.rankChangeTitle.up'")
    expect(leaderboardView).toContain('--token-bar-width')
    expect(leaderboardView).toContain('--token-input-width')
    expect(leaderboardView).toContain('--token-output-width')
    expect(leaderboardView).toContain('--token-cache-width')
    expect(leaderboardView).toContain('data-testid="leaderboard-rank-title"')
    expect(leaderboardView).toContain('function visibleLeaderboardTitleBadges')
