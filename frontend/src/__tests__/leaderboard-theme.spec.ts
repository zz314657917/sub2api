    expect(leaderboardView).toContain('max-height: 1.45rem')
    expect(leaderboardView).not.toContain('leaderboard-token-ranking-header')
    expect(leaderboardView).not.toContain('leaderboard.tokenRankingTitle')
    expect(leaderboardView).toContain('data-testid="leaderboard-token-tooltip"')
    expect(leaderboardView).toContain('function showTokenBarTooltip(item: UserLeaderboardItem, event: Event)')
    expect(leaderboardView).toContain('function leaderboardTokenTooltipMetrics(item: UserLeaderboardItem): TokenBarTooltipMetric[]')
    expect(leaderboardView).toContain('leaderboard-token-tooltip')
    expect(leaderboardView).toContain('leaderboard-token-tooltip-table')
    expect(leaderboardView).toContain('role="table"')
    expect(leaderboardView).not.toContain(':title="leaderboardTokenMetricsLabel(item)"')
    expect(leaderboardView).toContain(':aria-label="leaderboardTokenMetricsLabel(item)"')
