    expect(leaderboardView).toContain('function tokenBarStyle(item: UserLeaderboardItem): Record<string, string>')
    expect(leaderboardView).toContain('function leaderboardRankChangeLabel(item: UserLeaderboardItem): string')
    expect(leaderboardView).toContain('leaderboard-token-rank-name-line')
    expect(leaderboardView).toContain('data-testid="leaderboard-rank-change"')
